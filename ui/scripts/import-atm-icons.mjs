import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'

const source = resolve(process.argv[2] || process.env.ATM_ICON_SOURCE || '')
const project = resolve(import.meta.dirname, '..')
const target = join(project, 'public', 'icons', 'atm')
const manifestFile = join(project, 'src', 'assets', 'atmIconManifest.ts')
const freePattern = /^(ico|cat|ec|fam|fs|hpcd|mi|rph|sp|st|tt)_[0-9]{1,3}\.png$/
const premiumPattern = /^(flat|swift_colored_[a-z]+)_[0-9]{3}\.png$/
const pngSignature = '89504e470d0a1a0a'

if (!source || !existsSync(source) || !statSync(source).isDirectory()) {
  throw new Error('ATM icon source missing. Pass the unique-icons directory or set ATM_ICON_SOURCE.')
}

const entries = readdirSync(source, { withFileTypes: true })
  .filter(entry => entry.isFile() && (freePattern.test(entry.name) || premiumPattern.test(entry.name)))
  .map(entry => ({
    name: basename(entry.name, '.png'),
    file: entry.name,
    group: freePattern.test(entry.name) ? 'free' : 'premium',
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en'))

const names = new Set(entries.map(entry => entry.name))
if (names.size !== entries.length) throw new Error('ATM manifest contains duplicate icon names.')
if (entries.filter(entry => entry.group === 'free').length !== 847) throw new Error('Expected 847 Free icons (brand splash images excluded).')
if (entries.filter(entry => entry.group === 'premium').length !== 283) throw new Error('Expected 283 Premium icons.')

rmSync(target, { recursive: true, force: true })
mkdirSync(target, { recursive: true })
for (const entry of entries) {
  const input = join(source, entry.file)
  if (readFileSync(input).subarray(0, 8).toString('hex') !== pngSignature) throw new Error(`Invalid PNG: ${entry.name}`)
  copyFileSync(input, join(target, entry.file))
}

mkdirSync(resolve(manifestFile, '..'), { recursive: true })
const rows = entries.map(entry => `  { name: '${entry.name}', group: '${entry.group}' },`).join('\n')
writeFileSync(manifestFile, `// Generated by scripts/import-atm-icons.mjs; raw PNG files stay local-only.\nexport type AtmIconGroup = 'free' | 'premium'\nexport interface AtmIconEntry { name: string; group: AtmIconGroup }\nexport const ATM_ICON_ENTRIES: readonly AtmIconEntry[] = [\n${rows}\n]\nexport const ATM_ICON_NAMES = new Set(ATM_ICON_ENTRIES.map(entry => entry.name))\nexport const ATM_ICON_GROUP_BY_NAME = new Map(ATM_ICON_ENTRIES.map(entry => [entry.name, entry.group]))\nexport const atmIconPath = (name: string) => \`/icons/atm/\${name}.png\`\n`, 'utf8')
console.log(`ATM icons imported: Free=847 Premium=283 Total=${entries.length}`)
